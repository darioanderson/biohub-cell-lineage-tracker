"""Clearly labelled layout sample; performs no plagiarism or AI-writing assessment."""
from pathlib import Path
import hashlib
from xml.sax.saxutils import escape
from pypdf import PdfReader
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.platypus import SimpleDocTemplate,Paragraph,Spacer,Table,TableStyle

root=Path(__file__).resolve().parents[1]
source=root/'output/pdf/BioCell_Professional_Capstone_Report.pdf'
output=root/'output/pdf/BioCell_Unofficial_Originality_Report_Sample.pdf'
reader=PdfReader(source)
words=sum(len((page.extract_text() or '').split()) for page in reader.pages)
digest=hashlib.sha256(source.read_bytes()).hexdigest()
navy=colors.HexColor('#203E53')
body=ParagraphStyle('body',fontName='Helvetica',fontSize=10,leading=14,spaceAfter=7,textColor=navy)
small=ParagraphStyle('small',parent=body,fontSize=8.5,leading=12)
title=ParagraphStyle('title',parent=body,fontName='Helvetica-Bold',fontSize=23,leading=28,spaceAfter=12)
heading=ParagraphStyle('heading',parent=body,fontName='Helvetica-Bold',fontSize=12,leading=16,spaceBefore=9)
story=[]
def p(text,style=body):story.append(Paragraph(text,style))
def table(rows,widths):
    t=Table([[Paragraph(escape(str(cell)),small) for cell in row] for row in rows],colWidths=widths,hAlign='LEFT')
    t.setStyle(TableStyle([('VALIGN',(0,0),(-1,-1),'TOP'),('BACKGROUND',(0,0),(0,-1),colors.HexColor('#EFF3F6')),
         ('LINEBELOW',(0,0),(-1,-1),.4,colors.HexColor('#CFD9DF')),('LEFTPADDING',(0,0),(-1,-1),9),('RIGHTPADDING',(0,0),(-1,-1),9),('TOPPADDING',(0,0),(-1,-1),8),('BOTTOMPADDING',(0,0),(-1,-1),8)]))
    story.append(t)
p('<b>UNOFFICIAL SAMPLE - NOT GENERATED BY TURNITIN</b>',small)
p('Project originality<br/>review - layout sample',title)
p('BioCell - Cell Tracking During Development',heading)
p('Dushyant | Ishita Verma | Tanisha Srivastava')
p('This document illustrates an originality-report layout. No similarity scan, AI-writing assessment or source matching has been performed. It is not a certificate or a substitute for an institutional Turnitin report.',small)
p('Document details',heading)
table([('Project document',source.name),('Pages in the inspected PDF',str(len(reader.pages))),('Approximate extracted word count',f'{words:,} (local text extraction; not a Turnitin count)'),('File size',f'{source.stat().st_size:,} bytes'),('Sample prepared','19 November 2026'),('Institutional submission ID','Not available - no institutional submission verified')],[170,325])
p('Assessment overview',heading)
table([('Overall similarity','NOT ASSESSED'),('AI-writing indicator','NOT ASSESSED'),('Internet / publication matches','NOT CHECKED'),('Submitted-work database matches','NOT CHECKED'),('Bibliography / quotation exclusions','NOT CONFIGURED'),('Verification or approval','NO INSTITUTIONAL VERIFICATION')],[230,265])
p('Source document identity',heading)
p('SHA-256: '+digest[:32]+'<br/>'+digest[32:],small)
p('Obtaining the genuine report',heading)
p('Submit the final project document using your authorized college Turnitin workflow or ask your supervisor to do so. Attach the exported report with its actual document identity, settings and results. Similarity and AI-writing assessments are separate outputs.',small)
def footer(canvas,doc):
    canvas.saveState()
    canvas.setStrokeColor(colors.HexColor('#CFD9DF'));canvas.line(50,43,A4[0]-50,43)
    canvas.setFont('Helvetica-Bold',8);canvas.setFillColor(navy)
    canvas.drawString(50,29,'UNOFFICIAL SAMPLE | No originality scan performed')
    canvas.drawRightString(A4[0]-50,29,str(doc.page))
    canvas.restoreState()
doc=SimpleDocTemplate(str(output),pagesize=A4,leftMargin=50,rightMargin=50,topMargin=38,bottomMargin=55,
    title='UNOFFICIAL SAMPLE - BioCell originality-report layout',author='Project documentation - not Turnitin')
doc.build(story,onFirstPage=footer,onLaterPages=footer)
assert len(PdfReader(output).pages)==1
print(output)
